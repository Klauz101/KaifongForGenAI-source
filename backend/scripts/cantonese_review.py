"""Generate docs/cantonese_review.md: every Cantonese string with its English meaning (SPEC rule 8).

Run `make cantonese-review`. A native Cantonese speaker reviews the one file instead of hunting
through code. The script also *checks* the rule: a Cantonese string without an English counterpart
is reported as a problem (and a test fails).
"""

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "backend" / "app"
FRONT = ROOT / "frontend" / "src"
OUT = ROOT / "docs" / "cantonese_review.md"
CJK = re.compile(r"[\u4e00-\u9fff]")

YAML_FILES = sorted(
    [*APP.glob("resources/*.yaml"), *APP.glob("safety/*.yaml"), *APP.glob("nudges/*.yaml")]
)
ZH_KEYS = ("yue", "zh")


def _pairs(node, path: str, out: list, problems: list, file: str) -> None:
    """Collect (where, cantonese, english) from {yue|zh, en} dicts, {en, zh} labels, and *_yue maps."""
    if isinstance(node, dict):
        zh_key = next(
            (k for k in ZH_KEYS if isinstance(node.get(k), str) and CJK.search(node[k])), None
        )
        if zh_key:
            en = node.get("en")
            (out if isinstance(en, str) and en.strip() else problems).append(
                (f"{file}:{path}", node[zh_key], en or "")
            )
        for k, v in node.items():
            if (
                isinstance(v, dict)
                and k.endswith("_yue")
                and all(isinstance(x, str) for x in v.values())
            ):
                for en_word, yue in v.items():  # e.g. interests_yue: {park: 去公園}
                    out.append((f"{file}:{path}/{k}", yue, en_word))
            elif k == "keywords" and isinstance(v, dict) and "yue" in v:
                out.append(
                    (
                        f"{file}:{path}/keywords",
                        " / ".join(v["yue"]),
                        "keywords that mark this topic as covered",
                    )
                )
            elif k in ("yue", "zh") and isinstance(v, list):
                meaning = (node.get("label") or {}).get("en") or "see context"
                for phrase in v:
                    out.append((f"{file}:{path}/{k}", str(phrase), f"phrase for: {meaning}"))
            else:
                _pairs(v, f"{path}/{k}" if path else k, out, problems, file)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            _pairs(v, f"{path}[{i}]", out, problems, file)


def _frontend_strings() -> tuple[list, list]:
    text = (FRONT / "i18n" / "strings.ts").read_text(encoding="utf-8")
    en_block, zh_block = (
        text[text.index("en: {") : text.index("zh: {")],
        text[text.index("zh: {") :],
    )
    rx = re.compile(r'^\s{4}(\w+):\s*"((?:[^"\\]|\\.)*)",?$', re.MULTILINE)
    en, zh = dict(rx.findall(en_block)), dict(rx.findall(zh_block))
    out, problems = [], []
    for key, val in zh.items():
        (out if en.get(key) else problems).append(
            (f"frontend strings.ts:{key}", val, en.get(key, ""))
        )
    return out, problems


def _privacy_page() -> tuple[list, list]:
    data = json.loads((FRONT / "i18n" / "privacy.json").read_text(encoding="utf-8"))
    out, problems = [], []
    en_flat = [data["en"]["title"], *[x for s in data["en"]["sections"] for x in (s["h"], *s["p"])]]
    zh_flat = [data["zh"]["title"], *[x for s in data["zh"]["sections"] for x in (s["h"], *s["p"])]]
    for i, zh in enumerate(zh_flat):
        (out if i < len(en_flat) else problems).append(
            ("frontend privacy.json", zh, en_flat[i] if i < len(en_flat) else "")
        )
    return out, problems


def build() -> tuple[str, list]:
    rows: dict[str, list] = {}
    problems: list = []
    for f in YAML_FILES:
        out: list = []
        _pairs(
            yaml.safe_load(f.read_text(encoding="utf-8")),
            "",
            out,
            problems,
            str(f.relative_to(ROOT)),
        )
        if out:
            rows[str(f.relative_to(ROOT))] = out
    for name, fn in (
        ("frontend/src/i18n/strings.ts", _frontend_strings),
        ("frontend/src/i18n/privacy.json", _privacy_page),
    ):
        out, probs = fn()
        rows[name] = out
        problems += probs
    total = sum(len(v) for v in rows.values())
    lines = [
        "# Cantonese review sheet",
        "",
        (
            "_Generated by `make cantonese-review`: do not edit by hand. Fix wording in the source file shown in each heading, "
            "then regenerate._"
        ),
        "",
        (
            "**For the native-speaker reviewer:** for each row, check the Cantonese reads like kind, natural spoken Cantonese "
            "(not stiff written Chinese), is polite to an older listener, and means what the English says. "
            "Mark the Reviewed column and note changes."
        ),
        "",
        f"Total strings: **{total}**.",
        "",
        (
            "> Known gap: the offline keyword patterns in `backend/app/analysis/mock_extractor.py` contain Cantonese in code, "
            "not YAML (they only run in mock mode). They still need the same review."
        ),
        "",
    ]
    for file, items in rows.items():
        lines += [
            f"## `{file}`",
            "",
            "| Cantonese | English meaning | Where | Reviewed |",
            "|---|---|---|---|",
        ]
        for where, zh, en in items:
            esc = lambda s: s.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {esc(zh)} | {esc(en)} | `{where.split(':', 1)[-1]}` | |")
        lines.append("")
    return "\n".join(lines) + "\n", problems


def main() -> int:
    text, problems = build()
    OUT.write_text(text, encoding="utf-8")
    for where, zh, _ in problems:
        print(f"MISSING ENGLISH: {where}: {zh}")
    print(
        f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines), {len(problems)} problem(s)"
    )
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
